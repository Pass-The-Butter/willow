def execute_repair_v2():
    # Helper to actually get the data we need
    print("🤖 Generating repair plan (Verbose)...")
    report = detect_drift.execute(verbose=True)
    
    if not report['drift_detected']:
        print("✅ No drift detected.")
        return

    os.environ['SSL_CERT_FILE'] = certifi.where()
    driver = GraphDatabase.driver(NEO4J_URI, auth=(NEO4J_USER, NEO4J_PASSWORD))

    try:
        with driver.session() as session:
            # 1. Undocumented Skills
            undoc_skills = report['details']['skills'].get('undocumented_items', [])
            for skill in undoc_skills:
                # skill is a dict: {'name': ..., 'file': ..., 'reason': ...}
                print(f"   + Registering Skill: {skill['name']} ({skill['file']})")
                
                query = """
                MERGE (s:Skill {name: $name})
                SET s.code_path = $path,
                    s.language = 'python',
                    s.description = 'Auto-registered by Captain Willow Security Audit',
                    s.created_at = datetime(),
                    s.source_system = 'CaptainWillow-RepairDrift' 
                RETURN s
                """
                # Added source_system to comply with new policy spirit, though not strictly full provenance without event ID
                
                session.run(query, name=skill['name'], path=skill['file'])
                print("     -> Done")

            # 2. Check Relationship Type (Debug)
            print("\n🔍 Investigating Relationship Types...")
            rels = session.run("CALL db.relationshipTypes()")
            existing_types = [r['relationshipType'] for r in rels]
            print(f"   Existing types: {existing_types}")
            
            if 'SOURCE_FROM' not in existing_types:
                print("   ⚠️ 'SOURCE_FROM' does not exist.")
                # Suggest potential matches
                for t in existing_types:
                    if 'SOURCE' in t:
                        print(f"      Did you mean: {t}?")

    except Exception as e:
        print(f"❌ Error: {e}")
    finally:
        driver.close()

if __name__ == "__main__":
    execute_repair_v2()
